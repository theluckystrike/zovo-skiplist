export {};

import { sanitizeBackup } from "../skiplist/backup";
import {
    classifyLicenseResponse,
    hasValidProLicense,
    isProLicenseResponse,
    shouldRefreshLicense,
} from "../skiplist/license";

declare const __SUPABASE_ANON_KEY__: string;

// Storage values are intentionally heterogeneous at this browser-API boundary.
// eslint-disable-next-line @typescript-eslint/no-explicit-any
type AnyRecord = Record<string, any>;
const VERIFY_URL =
    "https://zgubxqomnbmxgbdhvwja.supabase.co/functions/v1/verify-extension-license";
const KEY_PATTERN = /^ZOVO-[A-Z0-9]{4}-[A-Z0-9]{4}-[A-Z0-9]{4}-[A-Z0-9]{4}$/i;

function element<T extends HTMLElement>(id: string): T {
    return document.getElementById(id) as T;
}
function get(
    area: chrome.storage.StorageArea,
    defaults: AnyRecord,
): Promise<AnyRecord> {
    return new Promise((resolve) => area.get(defaults, resolve));
}
function set(
    area: chrome.storage.StorageArea,
    values: AnyRecord,
): Promise<void> {
    return new Promise((resolve) => area.set(values, resolve));
}
function value(id: string): string {
    return element<HTMLInputElement | HTMLSelectElement>(id).value.trim();
}
function countBookmarks(collection: Record<string, unknown[]>): number {
    return Object.values(collection || {}).reduce(
        (sum, segments) => sum + (segments?.length || 0),
        0,
    );
}

async function hasPro(): Promise<boolean> {
    const local = await get(chrome.storage.local, {
        slp_license_status: "free",
        slp_license_key: "",
        slp_license_verified_at: 0,
        slp_license_exp: 0,
    });
    if (shouldRefreshLicense(local) && local.slp_license_key) {
        chrome.runtime.sendMessage({ message: "refreshLicense" }, () => {
            void chrome.runtime.lastError;
        });
    }
    return hasValidProLicense(local);
}

function message(text: string, good = false): void {
    const node = element("licenseMessage");
    node.textContent = text;
    node.style.color = good ? "#087f65" : "#a33b3b";
}

function profileFromForm(): AnyRecord {
    const categories = [
        ["sponsor", Number(value("profileSponsor"))],
        ["intro", Number(value("profileIntro"))],
        ["outro", Number(value("profileOutro"))],
        ["interaction", Number(value("profileInteraction"))],
        ["selfpromo", Number(value("profileSelfpromo"))],
        ["exclusive_access", -1],
        ["poi_highlight", 1],
        ["preview", -1],
        ["hook", -1],
        ["filler", -1],
        ["chapter", 0],
        ["music_offtopic", -1],
    ].map(([name, option]) => ({ name, option }));
    return {
        name: value("profileName") || "Listening profile",
        categorySelections: categories,
        showAutogeneratedChapters: null,
        showCreatorChapters: null,
        autoSkipOnMusicVideos: null,
        skipNonMusicOnlyOnYoutubeMusic: null,
        muteSegments: null,
        fullVideoSegments: null,
        manualSkipOnFullVideo: null,
        minDuration: null,
    };
}

async function renderProfiles(): Promise<void> {
    const local = await get(chrome.storage.local, { skipProfiles: {} });
    const list = element("profileList");
    list.replaceChildren();
    if (
        Object.keys(local.skipProfiles as Record<string, AnyRecord>).length ===
        0
    ) {
        const empty = document.createElement("p");
        empty.className = "slp-empty-list";
        empty.textContent = "No custom profiles yet. Save this one to begin.";
        list.append(empty);
        return;
    }
    for (const [id, profile] of Object.entries(
        local.skipProfiles as Record<string, AnyRecord>,
    )) {
        const row = document.createElement("div");
        row.className = "slp-listitem";
        const name = document.createElement("strong");
        name.textContent = profile.name || "Untitled profile";
        const remove = document.createElement("button");
        remove.type = "button";
        remove.textContent = "Remove";
        remove.setAttribute("aria-label", `Remove ${name.textContent}`);
        remove.addEventListener("click", async () => {
            const next = { ...local.skipProfiles };
            delete next[id];
            await set(chrome.storage.local, { skipProfiles: next });
            await renderProfiles();
        });
        row.append(name, remove);
        list.append(row);
    }
}

async function renderState(): Promise<void> {
    const [sync, local, pro] = await Promise.all([
        get(chrome.storage.sync, { minutesSaved: 0, skipCount: 0 }),
        get(chrome.storage.local, {
            unsubmittedSegments: {},
            podcastRules: {
                enabled: false,
                introSeconds: 45,
                outroSeconds: 30,
                titlePattern: "podcast|episode|interview",
            },
            slp_license_key: "",
        }),
        hasPro(),
    ]);
    const minutes = Math.round(Number(sync.minutesSaved) || 0);
    const skips = Number(sync.skipCount) || 0;
    const bookmarks = countBookmarks(local.unsubmittedSegments);
    element("statMinutes").textContent = String(minutes);
    element("statSkips").textContent = String(skips);
    element("statBookmarks").textContent = String(bookmarks);
    element("statsEmpty").hidden = minutes > 0 || skips > 0 || bookmarks > 0;
    element("statsGrid").hidden =
        minutes === 0 && skips === 0 && bookmarks === 0;
    element<HTMLInputElement>("podcastEnabled").checked = Boolean(
        local.podcastRules.enabled,
    );
    element<HTMLInputElement>("podcastPattern").value =
        local.podcastRules.titlePattern;
    element<HTMLInputElement>("podcastIntro").value = String(
        local.podcastRules.introSeconds,
    );
    element<HTMLInputElement>("podcastOutro").value = String(
        local.podcastRules.outroSeconds,
    );
    element<HTMLInputElement>("licenseKey").value = local.slp_license_key || "";
    element("licenseBadge").textContent = pro ? "PRO" : "FREE";
    await renderProfiles();
}

async function activateLicense(): Promise<void> {
    const key = value("licenseKey").toUpperCase();
    if (!KEY_PATTERN.test(key)) {
        message(
            "Use the format shown: four groups of four letters or numbers.",
        );
        return;
    }
    if (!__SUPABASE_ANON_KEY__) {
        message("This build is missing its publishable verification key.");
        return;
    }
    const controller = new AbortController();
    const timer = setTimeout(() => controller.abort(), 5000);
    try {
        const response = await fetch(VERIFY_URL, {
            method: "POST",
            headers: {
                "Content-Type": "application/json",
                apikey: __SUPABASE_ANON_KEY__,
            },
            body: JSON.stringify({ license_key: key, extension: "skiplist" }),
            signal: controller.signal,
        });
        const data: AnyRecord = await response.json();
        const decision = classifyLicenseResponse(response.ok, response.status, data);
        const pro = decision === "entitle" && isProLicenseResponse(response.ok, data);
        if (pro) {
            await set(chrome.storage.local, {
                slp_license_status: "pro",
                slp_license_key: key,
                slp_license_verified_at: Date.now(),
                // Zero means the verifier supplied no server expiry. The
                // seven-day offline verification window still applies.
                slp_license_exp: Number.isFinite(data.exp) && data.exp >= 0 ? data.exp : 0,
            });
        } else if (decision === "deny") {
            await set(chrome.storage.local, {
                slp_license_status: "free",
                slp_license_key: "",
                slp_license_verified_at: 0,
                slp_license_exp: 0,
            });
        }
        message(
            pro
                ? "License verified. Pro controls are active."
                : decision === "deny"
                    ? data.reason || data.error || "License not valid."
                    : (await hasPro())
                        ? "Verification unavailable. Using the recent verified license."
                        : "License verification is temporarily unavailable.",
            pro,
        );
        await renderState();
    } catch {
        message(
            (await hasPro())
                ? "Offline: using the recent verified license."
                : "Could not reach the license server.",
            await hasPro(),
        );
    } finally {
        clearTimeout(timer);
    }
}

document.addEventListener("DOMContentLoaded", () => {
    void renderState();
    element("saveProfile").addEventListener("click", async () => {
        const local = await get(chrome.storage.local, { skipProfiles: {} });
        if (Object.keys(local.skipProfiles).length >= 1 && !(await hasPro())) {
            message("Pro unlocks multiple category profiles.");
            element("licenseKey").focus();
            return;
        }
        const id = `slp-profile-${Date.now().toString(36)}`;
        await set(chrome.storage.local, {
            skipProfiles: { ...local.skipProfiles, [id]: profileFromForm() },
        });
        await renderProfiles();
    });
    element("savePodcast").addEventListener("click", async () => {
        if (!(await hasPro())) {
            message("Activate Pro to enable podcast rules.");
            element("licenseKey").focus();
            return;
        }
        const podcastRules = {
            enabled: element<HTMLInputElement>("podcastEnabled").checked,
            titlePattern:
                value("podcastPattern") || "podcast|episode|interview",
            introSeconds: Math.min(
                600,
                Math.max(0, Number(value("podcastIntro")) || 0),
            ),
            outroSeconds: Math.min(
                600,
                Math.max(0, Number(value("podcastOutro")) || 0),
            ),
        };
        await set(chrome.storage.local, { podcastRules });
        if (podcastRules.enabled) {
            const sync = await get(chrome.storage.sync, {
                categorySelections: [],
            });
            const selections = [...sync.categorySelections];
            for (const name of ["intro", "outro"]) {
                const existing = selections.find(
                    (item: AnyRecord) => item.name === name,
                );
                if (existing) existing.option = 2;
                else selections.push({ name, option: 2 });
            }
            await set(chrome.storage.sync, { categorySelections: selections });
        }
        message("Podcast rules saved locally.", true);
    });
    element("activateLicense").addEventListener(
        "click",
        () => void activateLicense(),
    );
    element("exportData").addEventListener("click", async () => {
        const [sync, local] = await Promise.all([
            get(chrome.storage.sync, {}),
            get(chrome.storage.local, {}),
        ]);
        const data = {
            format: "skiplist-personal-1",
            exportedAt: new Date().toISOString(),
            sync: {
                minutesSaved: sync.minutesSaved,
                skipCount: sync.skipCount,
                categorySelections: sync.categorySelections,
            },
            local: {
                unsubmittedSegments: local.unsubmittedSegments,
                skipProfiles: local.skipProfiles,
                podcastRules: local.podcastRules,
            },
        };
        const url = URL.createObjectURL(
            new Blob([JSON.stringify(data, null, 2)], {
                type: "application/json",
            }),
        );
        const link = document.createElement("a");
        link.href = url;
        link.download = "skiplist-backup.json";
        link.click();
        URL.revokeObjectURL(url);
    });
    element<HTMLInputElement>("importData").addEventListener(
        "change",
        async (event) => {
            const file = (event.target as HTMLInputElement).files?.[0];
            if (!file) return;
            try {
                const data = sanitizeBackup(JSON.parse(await file.text()));
                if (!data) throw new Error();
                // Validation is complete before either storage area is
                // touched, so malformed backups cannot partially import.
                await set(chrome.storage.sync, data.sync);
                await set(chrome.storage.local, data.local);
                message("Backup imported.", true);
                await renderState();
            } catch {
                message("That file is not a SkipList backup.");
            }
        },
    );
});

chrome.storage.onChanged.addListener((changes, areaName) => {
    if (areaName === "local" && [
        "slp_license_status",
        "slp_license_verified_at",
        "slp_license_exp",
    ].some((key) => key in changes)) void renderState();
});
