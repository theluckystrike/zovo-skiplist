import { sanitizeBackup } from "../src/skiplist/backup";

function validBackup() {
    return {
        format: "skiplist-personal-1",
        sync: {
            minutesSaved: 3,
            skipCount: 2,
            categorySelections: [{ name: "intro", option: 2 }],
        },
        local: {
            unsubmittedSegments: {
                abc12345678: [{
                    segment: [1, 2],
                    UUID: "local-1",
                    category: "intro",
                    actionType: "skip",
                    source: 1,
                }],
            },
            skipProfiles: {
                first: {
                    name: "First",
                    categorySelections: [{ name: "intro", option: 2 }],
                    showAutogeneratedChapters: null,
                    showCreatorChapters: null,
                    autoSkipOnMusicVideos: null,
                    skipNonMusicOnlyOnYoutubeMusic: null,
                    muteSegments: null,
                    fullVideoSegments: null,
                    manualSkipOnFullVideo: null,
                    minDuration: null,
                },
            },
            podcastRules: {
                enabled: true,
                introSeconds: 45,
                outroSeconds: 30,
                titlePattern: "podcast|episode",
            },
        },
    };
}

describe("SkipList backup validation", () => {
    it("sanitizes a complete valid backup and omits license fields", () => {
        const input = validBackup() as Record<string, any>;
        input.local.slp_license_status = "pro";
        input.local.slp_license_key = "ZOVO-EVIL-EVIL-EVIL-EVIL";
        const output = sanitizeBackup(input);
        expect(output).not.toBeNull();
        expect(output?.local).not.toHaveProperty("slp_license_status");
        expect(output?.local).not.toHaveProperty("slp_license_key");
    });

    test.each([
        (data: Record<string, any>) => { data.sync.minutesSaved = Infinity; },
        (data: Record<string, any>) => { data.local.skipProfiles.first = null; },
        (data: Record<string, any>) => { data.local.podcastRules.introSeconds = 601; },
        (data: Record<string, any>) => { data.local.unsubmittedSegments.abc12345678[0].segment = [3, 2]; },
        (data: Record<string, any>) => { data.sync.categorySelections[0].option = 99; },
    ])("rejects malformed nested data %#", (mutate) => {
        const input = validBackup();
        mutate(input);
        expect(sanitizeBackup(input)).toBeNull();
    });
});
